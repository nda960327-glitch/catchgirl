/**
 * 사업자등록번호 검사 — 000-00-00000 열 자리, 국세청 검증 가중치.
 * 숫자만 맞으면 통과하는 게 아니라 마지막 자리(검증번호)까지 맞아야 한다.
 */
export function normalizeBizNumber(raw: string) {
  return raw.replace(/\D/g, "");
}
export function formatBizNumber(raw: string) {
  const d = normalizeBizNumber(raw);
  return d.length === 10 ? `${d.slice(0, 3)}-${d.slice(3, 5)}-${d.slice(5)}` : raw;
}
export function isValidBizNumber(raw: string) {
  const d = normalizeBizNumber(raw);
  if (!/^\d{10}$/.test(d)) return false;
  const w = [1, 3, 7, 1, 3, 7, 1, 3, 5];
  let sum = 0;
  for (let i = 0; i < 9; i++) sum += Number(d[i]) * w[i];
  sum += Math.floor((Number(d[8]) * 5) / 10);
  return (10 - (sum % 10)) % 10 === Number(d[9]);
}

/** 콘솔·관리자 화면에 같은 문장으로 — "확인 대기" 인 매장은 열지 않는다 */
export function bizStatus(store: { bizVerifiedAt: Date | null; bizNumber: string; termsAgreedAt: Date | null; termsVersion: string }) {
  const verified = !!store.bizVerifiedAt;
  const agreed = !!store.termsAgreedAt;
  const outdated = agreed && store.termsVersion !== TERMS_VERSION;
  return { verified, agreed, outdated, hasDoc: !!store.bizNumber };
}
